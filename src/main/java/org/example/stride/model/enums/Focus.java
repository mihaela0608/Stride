package org.example.stride.model.enums;

public enum Focus {
    BASE,       // Focus on aerobic mileage and tissue resilience
    BUILD,      // Focus on increasing intensity, intervals, or tempo work
    PEAK,       // Maximum specific race-pace simulation and high load
    RECOVERY,   // Reduced volume and intensity to absorb training stress (deload)
    TAPER,      // Lower volume while maintaining intensity before a race
    RACE,       // Race week containing competition and specific recovery
    OFF_SEASON  // Unstructured cross-training or active rest
}
